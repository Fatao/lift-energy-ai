export const DICT: Record<Lang, Record<Key, string>> = { en: en as unknown as Record<Key, string>, ru };

export interface I18n {
  lang: Lang;
  t: (key: Key, vars?: Record<string, string | number>) => string;
  /** number with a fixed number of decimals in the language's own style */
  n: (x: number | null | undefined, d?: number) => string;
  rub: (x: number | null | undefined) => string;
}

export function makeI18n(lang: Lang): I18n {
  const loc = lang === "ru" ? "ru-RU" : "en-US";
  return {
    lang,
    t: (key, vars) => {
      let s = DICT[lang][key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
      return s;
    },
    n: (x, d = 1) => (x == null ? "—" : x.toLocaleString(loc, { maximumFractionDigits: d, minimumFractionDigits: d })),
    rub: (x) => (x == null ? "—" : Math.round(x).toLocaleString(loc) + " ₽"),
  };
}

export const I18nCtx = createContext<I18n>(makeI18n("ru"));
export const useI18n = () => useContext(I18nCtx);